create table if not exists app_users
(
    id                bigint generated by default as identity
    primary key,
    is_active         boolean      not null,
    created_at        timestamp(6) not null,
    last_seen_at      timestamp(6),
    updated_at        timestamp(6) not null,
    status            varchar(50),
    username          varchar(50)  not null
    unique,
    display_name      varchar(100) not null,
    profile_image_url varchar(500),
    password          varchar(255) not null
    );

create table if not exists chat_rooms
(
    id          bigint generated by default as identity
    primary key,
    is_active   boolean      not null,
    max_members integer      not null,
    created_at  timestamp(6) not null,
    created_by  bigint       not null
    constraint fkoo8wefq27qa0gl1vp6q5ynam3
    references app_users,
    updated_at  timestamp(6) not null,
    type        varchar(20)  not null
    constraint chat_rooms_type_check
    check ((type)::text = ANY
((ARRAY ['DIRECT'::character varying, 'GROUP'::character varying, 'CHANNEL'::character varying])::text[])),
    name        varchar(100) not null,
    image_url   varchar(500),
    description text
    );

create table if not exists chat_room_members
(
    id                   bigint generated by default as identity
    primary key,
    is_active            boolean      not null,
    chat_room_id         bigint       not null
    constraint fk6x7kwk21yt5odfxv5ubbrmo0h
    references chat_rooms,
    created_at           timestamp(6) not null,
    joined_at            timestamp(6) not null,
    last_read_message_id bigint,
    left_at              timestamp(6),
    user_id              bigint       not null
    constraint fksvx2k685ure1beo5hd579xg9y
    references app_users,
    role                 varchar(20)  not null
    constraint chat_room_members_role_check
    check ((role)::text = ANY
((ARRAY ['OWNER'::character varying, 'ADMIN'::character varying, 'MEMBER'::character varying])::text[])),
    unique (chat_room_id, user_id)
    );

create index if not exists idx_chat_room_member_user_id
    on chat_room_members (user_id);

create index if not exists idx_chat_room_member_chat_room_id
    on chat_room_members (chat_room_id);

create index if not exists idx_chat_room_member_active
    on chat_room_members (is_active);

create index if not exists idx_chat_room_member_role
    on chat_room_members (role);

create index if not exists idx_chat_room_created_by
    on chat_rooms (created_by);

create index if not exists idx_chat_room_type
    on chat_rooms (type);

create index if not exists idx_chat_room_active
    on chat_rooms (is_active);

create table if not exists messages
(
    id              bigint generated by default as identity
    primary key,
    is_deleted      boolean      not null,
    is_edited       boolean      not null,
    chat_room_id    bigint       not null
    constraint fk67lyatc9udvn9fgepx08ckmbt
    references chat_rooms,
    created_at      timestamp(6) not null,
    edited_at       timestamp(6),
    sender_id       bigint       not null
    constraint fkiwmjso15wbkeq7hkvg6noqh5v
    references app_users,
    sequence_number bigint       not null,
    type            varchar(20)  not null
    constraint messages_type_check
    check ((type)::text = ANY ((ARRAY ['TEXT'::character varying, 'SYSTEM'::character varying])::text[])),
    content         text
    );

create index if not exists idx_message_chat_room_id
    on messages (chat_room_id);

create index if not exists idx_message_sender_id
    on messages (sender_id);

create index if not exists idx_message_created_at
    on messages (created_at);

create index if not exists idx_message_room_time
    on messages (chat_room_id, created_at);

create index if not exists idx_message_room_sequence
    on messages (chat_room_id, sequence_number);